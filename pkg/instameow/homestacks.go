package instameow

// IsConnected reports whether the iris socket is currently subscribed (the
// same flag the client waits on internally). It is true from the subscribe
// acknowledgement until the socket drops. Added by homestacks for held
// messages, which must not be released into a dead connection.
func (c *Client) IsConnected() bool {
	return c.connected.IsSet()
}
